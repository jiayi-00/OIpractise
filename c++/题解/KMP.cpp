#include<bits/stdc++.h>
#define int long long
using namespace std;

char s1[1000005],s2[1000005];	// s1：文本串（主串）  s2：模式串（待匹配串）
int p[1000005],ans[1000005];	// p[i]：s2[1..i] 的最长「真前缀 = 真后缀」长度，即 KMP 的 next 数组
								// ans：每次匹配成功时，模式串在文本串中的起始下标（1 起）
int cnt;						// 匹配成功的次数

signed main(){
	// 从下标 1 开始存放字符（s[0] 闲置），后面全部按 1-based 处理，避免越界
	scanf("%s",s1+1);
	scanf("%s",s2+1);
	int n1=strlen(s1+1),n2=strlen(s2+1);

	/* ========== 第一步：预处理模式串 s2，求 next 数组 p[] ========== */
	p[1]=0;						// 长度为 1 的串不存在「真前后缀」，next 值为 0
	int j=0;					// j：当前已匹配的前缀长度，即 s2[1..j] 与当前位置结尾的子串对齐
	for(int i = 1; i < n2; i++) {
		// 失配：不断把 j 回退到更短的候选前缀，直到能接上当前字符，或回退到 0
		while (j != 0 && s2[j+1] != s2[i+1]) {
			j=p[j];				// 回退：已匹配前缀 s2[1..j] 的最长真前后缀长度就是下一个候选
		}
		if (s2[i+1] == s2[j+1]){// 匹配成功：最长真前后缀长度 +1
			p[i+1]=j+1;			// s2[1..i+1] 的最长真前后缀长度为 j+1
			j++;				// 已匹配前缀长度 +1，为下一轮做准备
		}
		// 若一直回退到 j==0 仍失配，则 p[i+1] 保持 0（全局变量默认初值为 0）
	}

	/* ========== 第二步：用 next 数组在文本串 s1 中匹配 s2 ========== */
	j=0;						// j 仍表示「当前已匹配的模式串前缀长度」
	for(int i = 0; i < n1; i++) {
		// 失配时按 next 回退，跳过所有不可能成功的起点（主串指针 i 永不回退，这是 KMP 高效的关键）
		while (j != 0 && s2[j+1] != s1[i+1]) {
			j=p[j];
		}
		if(s1[i+1] == s2[j+1]) {// 当前字符对上了
			j++;				// 已匹配长度 +1
			if(j == n2) {		// 模式串全部匹配完成
				// i+1 是当前字符在 s1 中的 1-based 下标，减去模式串长度再加 1 即本次匹配的起始位置
				ans[++cnt]=i+1-n2+1;
				j=p[j];			// 回退到最长真前后缀，继续找下一次匹配（因此支持重叠匹配）
			}
		}
	}

	/* ========== 第三步：输出结果 ========== */
	for(int i = 1; i <= cnt; i++){
		cout << ans[i] << '\n';	// 依次输出每次匹配的起始下标
	}
	for(int i = 1; i <= n2; i++){
		cout << p[i] <<' ';		// 输出模式串的 next 数组（洛谷 P3375 要求的格式）
	}
	return 0;
}
